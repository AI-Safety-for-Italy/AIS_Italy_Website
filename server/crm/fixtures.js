/** The rows of a fixture sheet, as the Sheets API returns them. */
function values(sourceId) {
  const sheet = SHEETS[sourceId];
  if (!sheet) throw new Error(`No fixture for ${sourceId}`);
  // A copy, so a test cannot change what the next one reads.
  return sheet.map((row) => row.slice());
}

